// 도장 12종(p01–p06은 화면 설계 '도장 6종'·'도장 컴포넌트' 보드, p07–p12는 2026-10-30 추가). public/images/stamps/의 SVG 원본을 JSX로 옮겼다.
// - 기본: 원형 테두리 두 줄 + 그림 + 문구. 원본은 지름 190px 기준이고 size에 맞춰 통째로 확대·축소한다.
// - mini: 달력·최근 기록용. 문구와 안쪽 점선 없이 원형 틀과 그림만, tilt로 기울인다.
// 색은 currentColor(도장마다 text-stamp-pXX), 문구 글꼴은 페이지의 Gaegu(font-hand),
// 거친 선은 CrayonFilters의 #stamp-rough 필터를 쓴다.

type StampText = { x: number; y: number; size: number; rotate: number; text: string };

type StampBase = {
  name: string;
  color: string;
  // 그림(200×200 좌표). mini는 이 그림을 artTransform.mini로 놓는다.
  art: ReactNode;
};

// 기본 도장도 같은 그림을 위치·크기만 바꿔 놓는 도장(p01–p06, p11)
type ComposedStamp = StampBase & {
  // 기본 도장 전체를 기울이는 각도
  tilt: number;
  artTransform: { full: string; mini: string };
  // 기본 도장에만 있는 장식(테두리 좌표 기준)
  extra?: ReactNode;
  // 문구 글자(190×190 좌표). 원본 SVG의 글자별 위치·회전 그대로
  texts: StampText[];
};

// 기본 도장을 원본(Figma 내보내기)의 그림·글자 그대로 그리는 도장(p07–p10, p12).
// 원본은 기울기가 그림·글자 좌표에 이미 들어 있고(190×190), 테두리 두 줄만 공통 원으로 그린다.
type DrawnStamp = StampBase & {
  artTransform: { mini: string };
  drawing: ReactNode;
  // <text>(transform·fontSize)와 <tspan>(x·y). 원본 좌표 그대로
  lettering: ReactNode;
};

type StampDesign = ComposedStamp | DrawnStamp;

